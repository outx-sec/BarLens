#!/bin/bash
#
# Build BarLens.app.
#
# The signing identity matters more than usual here. BarLens needs the
# Accessibility permission to enumerate menu bar items, and macOS keys that
# grant to the app's code signature. Under an ad-hoc signature the identity is
# the cdhash alone, which changes on every build — so every rebuild looks like
# a brand new app and the grant has to be given again. Worse, a stale cdhash
# requirement left in the TCC database stops the grant from ever matching.
#
# Signing with a stable local certificate makes the designated requirement
# `identifier "…" and certificate leaf = H"…"`, which survives rebuilds.
#
# Create the certificate once, if `security find-identity -v -p codesigning`
# does not list "BarLens Dev":
#
#   read -rsp "Temporary PKCS#12 password: " CERT_PASS && echo
#   openssl req -x509 -newkey rsa:2048 -sha256 -days 3650 -nodes \
#     -keyout key.pem -out cert.pem -config <(printf '%s\n' \
#       '[req]' 'distinguished_name=dn' 'x509_extensions=codesign' 'prompt=no' \
#       '[dn]' 'CN=BarLens Dev' \
#       '[codesign]' 'basicConstraints=critical,CA:false' \
#       'keyUsage=critical,digitalSignature' 'extendedKeyUsage=critical,codeSigning')
#   openssl pkcs12 -export -legacy -out dev.p12 -inkey key.pem -in cert.pem -passout env:CERT_PASS
#   security import dev.p12 -k ~/Library/Keychains/login.keychain-db -P "$CERT_PASS" -T /usr/bin/codesign
#   security add-trusted-cert -r trustRoot -p codeSign \
#     -k ~/Library/Keychains/login.keychain-db cert.pem
#   rm -f key.pem cert.pem dev.p12
#   unset CERT_PASS
#
# The `-legacy` flag matters: macOS cannot read the PKCS#12 defaults OpenSSL 3
# writes and reports the failure as a wrong password. The final
# `add-trusted-cert` is what turns it into a *valid* identity — without it
# codesign still signs, but System Settings refuses to register the app.
#
set -euo pipefail
cd "$(dirname "$0")"

CONFIG="${CONFIG:-debug}"

if [ -n "${CODE_SIGN_IDENTITY:-}" ]; then
    IDENTITY="$CODE_SIGN_IDENTITY"
elif security find-identity -v -p codesigning | grep -q "BarLens Dev"; then
    IDENTITY="BarLens Dev"
elif security find-identity -v -p codesigning | grep -q "MenuBarDivider Dev"; then
    IDENTITY="MenuBarDivider Dev"
else
    echo "warning: signing identity 'BarLens Dev' not found; falling back to ad-hoc signing ('-')." >&2
    echo "         Note: ad-hoc builds change cdhash on every rebuild, so macOS will prompt" >&2
    echo "         for Accessibility permission again after each rebuild. See build.sh header" >&2
    echo "         to create a persistent local certificate." >&2
    IDENTITY="-"
fi

swift build -c "$CONFIG"
BIN="$(swift build -c "$CONFIG" --show-bin-path)"

# Installed to /Applications on purpose. MenuBarAgent files status items under
# the owning app's bundle identifier only when LaunchServices knows the bundle,
# which it only does for apps in an installed location. It looks items up by
# bundle identifier while a visibility restriction is active, so an app run from
# a build directory gets its dividers filed under the process name and they are
# silently dropped from the bar. Measured both ways — see DividerController.
APP="${INSTALL_DIR:-/Applications}/BarLens.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN/BarLens" "$APP/Contents/MacOS/BarLens"
# The helper holds the MenuBarAgent restriction. It ships inside the bundle so
# there is no second login item to register — autostarting the app starts it.
cp "$BIN/BarLensAgent" "$APP/Contents/MacOS/BarLensAgent"
if [ "$CONFIG" = "release" ]; then
    strip -x "$APP/Contents/MacOS/BarLens" "$APP/Contents/MacOS/BarLensAgent"
fi
cp Resources/Info.plist "$APP/Contents/Info.plist"
# Generated by Tools/make-icon.swift and checked in; the script is not run on
# every build so the icon cannot change without someone meaning it to.
cp Resources/AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"

# A com.apple.macl attribute copied along with the bundle makes TCC refuse to
# register the app, so strip extended attributes before signing.
xattr -cr "$APP" 2>/dev/null || true

codesign --force --sign "$IDENTITY" --identifier com.barlens.app "$APP"
codesign --verify --deep --strict "$APP"

echo "built $APP"
